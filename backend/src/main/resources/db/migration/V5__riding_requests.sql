CREATE TABLE riding_requests (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES app_users(id),
 kind VARCHAR(20) NOT NULL CHECK(kind IN ('SUGGESTION','ROOM')),
 title VARCHAR(120) NOT NULL, description VARCHAR(2000) NOT NULL DEFAULT '',
 contact VARCHAR(120) NOT NULL, room VARCHAR(40) NOT NULL DEFAULT '',
 usage VARCHAR(20) NOT NULL DEFAULT '', other_usage VARCHAR(200) NOT NULL DEFAULT '',
 starts_at TIMESTAMPTZ, ends_at TIMESTAMPTZ,
 status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK(status IN ('PENDING','APPROVED','REJECTED')),
 review_note VARCHAR(500) NOT NULL DEFAULT '', reviewed_at TIMESTAMPTZ,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CHECK(kind <> 'ROOM' OR (starts_at IS NOT NULL AND ends_at > starts_at))
);
CREATE INDEX riding_requests_user_created ON riding_requests(user_id,created_at DESC);
