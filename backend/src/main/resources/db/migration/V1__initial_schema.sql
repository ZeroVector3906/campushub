CREATE TABLE app_users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 username VARCHAR(32) NOT NULL UNIQUE,
 password_hash VARCHAR(100) NOT NULL,
 name VARCHAR(50) NOT NULL,
 email VARCHAR(120) NOT NULL UNIQUE,
 student_no VARCHAR(30) NOT NULL,
 department VARCHAR(100) NOT NULL,
 bio VARCHAR(500) NOT NULL DEFAULT '',
 role VARCHAR(20) NOT NULL CHECK (role IN ('STUDENT','ADMIN')),
 enabled BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE clubs (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(80) NOT NULL UNIQUE,
 category VARCHAR(30) NOT NULL,
 summary VARCHAR(160) NOT NULL,
 description TEXT NOT NULL,
 icon VARCHAR(30) NOT NULL,
 color VARCHAR(20) NOT NULL,
 location VARCHAR(100) NOT NULL,
 contact VARCHAR(100) NOT NULL,
 recruiting BOOLEAN NOT NULL DEFAULT TRUE,
 active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE memberships (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES app_users(id),
 club_id BIGINT NOT NULL REFERENCES clubs(id),
 reason VARCHAR(1000) NOT NULL,
 status VARCHAR(20) NOT NULL CHECK (status IN ('PENDING','APPROVED','REJECTED','WITHDRAWN')),
 review_note VARCHAR(500) NOT NULL DEFAULT '',
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 reviewed_at TIMESTAMPTZ,
 UNIQUE(user_id,club_id)
);
CREATE TABLE activities (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 club_id BIGINT NOT NULL REFERENCES clubs(id),
 title VARCHAR(120) NOT NULL,
 category VARCHAR(30) NOT NULL,
 description TEXT NOT NULL,
 location VARCHAR(120) NOT NULL,
 starts_at TIMESTAMPTZ NOT NULL,
 ends_at TIMESTAMPTZ NOT NULL,
 registration_deadline TIMESTAMPTZ NOT NULL,
 capacity INTEGER NOT NULL CHECK(capacity > 0),
 checkin_code VARCHAR(32) NOT NULL,
 featured BOOLEAN NOT NULL DEFAULT FALSE,
 status VARCHAR(20) NOT NULL CHECK(status IN ('PUBLISHED','CANCELLED')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CHECK(ends_at > starts_at), CHECK(registration_deadline <= starts_at)
);
CREATE TABLE registrations (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES app_users(id),
 activity_id BIGINT NOT NULL REFERENCES activities(id),
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 checked_in_at TIMESTAMPTZ,
 UNIQUE(user_id,activity_id)
);
CREATE TABLE equipment (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(100) NOT NULL,
 category VARCHAR(40) NOT NULL,
 asset_code VARCHAR(50) NOT NULL UNIQUE,
 description VARCHAR(1000) NOT NULL,
 location VARCHAR(100) NOT NULL,
 total_quantity INTEGER NOT NULL CHECK(total_quantity >= 0),
 available_quantity INTEGER NOT NULL CHECK(available_quantity >= 0 AND available_quantity <= total_quantity),
 active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE loans (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES app_users(id),
 equipment_id BIGINT NOT NULL REFERENCES equipment(id),
 quantity INTEGER NOT NULL CHECK(quantity > 0),
 purpose VARCHAR(500) NOT NULL,
 due_date DATE NOT NULL,
 status VARCHAR(30) NOT NULL CHECK(status IN ('PENDING','APPROVED','REJECTED','RETURN_PENDING','RETURNED','CANCELLED')),
 review_note VARCHAR(500) NOT NULL DEFAULT '',
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 returned_at TIMESTAMPTZ
);
CREATE TABLE repair_tickets (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES app_users(id),
 equipment_id BIGINT REFERENCES equipment(id),
 title VARCHAR(120) NOT NULL,
 description VARCHAR(2000) NOT NULL,
 location VARCHAR(120) NOT NULL,
 priority VARCHAR(20) NOT NULL CHECK(priority IN ('LOW','NORMAL','HIGH')),
 status VARCHAR(20) NOT NULL CHECK(status IN ('OPEN','PROCESSING','RESOLVED','CLOSED')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE repair_updates (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 ticket_id BIGINT NOT NULL REFERENCES repair_tickets(id),
 operator_name VARCHAR(50) NOT NULL,
 status VARCHAR(20) NOT NULL,
 note VARCHAR(1000) NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_memberships_status ON memberships(status);
CREATE INDEX idx_activities_start ON activities(starts_at);
CREATE INDEX idx_registrations_activity ON registrations(activity_id);
CREATE INDEX idx_loans_status ON loans(status);
CREATE INDEX idx_repairs_status ON repair_tickets(status);
CREATE INDEX idx_repair_updates_ticket ON repair_updates(ticket_id);
CREATE TABLE SPRING_SESSION (
 PRIMARY_ID CHAR(36) NOT NULL PRIMARY KEY,
 SESSION_ID CHAR(36) NOT NULL,
 CREATION_TIME BIGINT NOT NULL,
 LAST_ACCESS_TIME BIGINT NOT NULL,
 MAX_INACTIVE_INTERVAL INT NOT NULL,
 EXPIRY_TIME BIGINT NOT NULL,
 PRINCIPAL_NAME VARCHAR(100)
);
CREATE UNIQUE INDEX SPRING_SESSION_IX1 ON SPRING_SESSION(SESSION_ID);
CREATE INDEX SPRING_SESSION_IX2 ON SPRING_SESSION(EXPIRY_TIME);
CREATE INDEX SPRING_SESSION_IX3 ON SPRING_SESSION(PRINCIPAL_NAME);
CREATE TABLE SPRING_SESSION_ATTRIBUTES (
 SESSION_PRIMARY_ID CHAR(36) NOT NULL REFERENCES SPRING_SESSION(PRIMARY_ID) ON DELETE CASCADE,
 ATTRIBUTE_NAME VARCHAR(200) NOT NULL,
 ATTRIBUTE_BYTES BYTEA NOT NULL,
 PRIMARY KEY(SESSION_PRIMARY_ID, ATTRIBUTE_NAME)
);
